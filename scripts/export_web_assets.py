"""Keep the web demo in lock-step with the Python engine.

Writes, from the single source of truth in fse/ and prompts/:
  web/src/generated/schema.json        the Extraction JSON Schema (also the Claude tool schema)
  web/src/generated/prompt.ts          the versioned prompt template
  web/src/generated/demo-results.json  real outputs from running the CLI over samples/ (rules mode)
  web/public/samples/*                 the sample documents, downloadable from the demo

python scripts/export_web_assets.py
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

from fse.llm import PROMPT_DIR, PROMPT_VERSION
from fse.pipeline import extract_file
from fse.schema import tool_schema

ROOT = Path(__file__).resolve().parent.parent
GEN = ROOT / "web" / "src" / "generated"
PUB = ROOT / "web" / "public" / "samples"


def main():
    GEN.mkdir(parents=True, exist_ok=True)
    PUB.mkdir(parents=True, exist_ok=True)

    (GEN / "schema.json").write_text(json.dumps(tool_schema(), indent=2) + "\n")
    prompt = (PROMPT_DIR / f"{PROMPT_VERSION}.md").read_text()
    (GEN / "prompt.ts").write_text(
        "// Generated by scripts/export_web_assets.py from prompts/. Do not edit.\n"
        f"export const PROMPT_VERSION = {json.dumps(PROMPT_VERSION)};\n"
        f"export const PROMPT_TEMPLATE = {json.dumps(prompt)};\n"
    )

    results = []
    for f in sorted((ROOT / "samples").iterdir()):
        if f.suffix.lower() in {".pdf", ".xlsx", ".csv"}:
            r = extract_file(f, mode="rules")
            r.pop("sha256", None)
            results.append(r)
            shutil.copy2(f, PUB / f.name)
    (GEN / "demo-results.json").write_text(json.dumps(results, indent=2) + "\n")
    print(f"Exported schema, prompt and {len(results)} demo results")


if __name__ == "__main__":
    main()
